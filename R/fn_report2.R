# R/fn_report2.R — HTML v2 report with AI hints and direct LLM sending.
# Semantic sections (data-ai-role) + structured JSON block at the end.

# Generates a JSON block with summarised data for an LLM to interpret.
# Embedded as <script type="application/json" id="acustera_ai_context">
ai_context_json <- function(features, lmm = NULL, posthoc = NULL,
                             conv_lmm = NULL, lex = NULL,
                             selected_examples = NULL, notes = "",
                             sess_meta = NULL) {
  safe <- function(x) if (is.null(x) || (is.numeric(x) && !is.finite(x))) NA else x
  desc <- if (!is.null(features) && nrow(features) > 0) {
    features |>
      dplyr::filter(speaker %in% c("man","woman","therapist")) |>
      dplyr::group_by(couple, therapy_num, speaker) |>
      dplyr::summarise(n = dplyr::n(),
                       F0_M  = round(mean(f0_mean,  na.rm = TRUE), 1),
                       F0_SD = round(sd(f0_mean,    na.rm = TRUE), 1),
                       INT_M = round(mean(intensity_mean, na.rm = TRUE), 1),
                       .groups = "drop")
  } else NULL
  lmm_sig <- if (!is.null(lmm) && nrow(lmm) > 0)
    lmm |> dplyr::filter(!is.na(p_adj), p_adj < 0.05) else NULL
  post_sig <- if (!is.null(posthoc) && nrow(posthoc) > 0)
    posthoc |> dplyr::filter(!is.na(p.value), p.value < 0.05) else NULL

  payload <- list(
    generated_at = format(Sys.time(), "%Y-%m-%d %H:%M:%S"),
    hypothesis   = trimws(notes),
    descriptives = desc,
    significant_lmm = lmm_sig,
    significant_posthoc = post_sig,
    lmm_convergence   = conv_lmm,
    linguistics        = lex,
    selected_examples = selected_examples
  )
  jsonlite::toJSON(payload, auto_unbox = TRUE, na = "null",
                   pretty = TRUE, force = TRUE)
}

# Prompt template that the user can copy to the LLM chat.
ai_prompt_template <- function() {
"You are a clinical research methodological reviewer. I am attaching an acoustic analysis report of longitudinal couple therapy generated by the AcusTera app, with a structured JSON block at the end (#acustera_ai_context).

Task:
1. Summarise the main findings (effect sizes, direction, adjusted significance).
2. Interpret the prosodic convergence between patient(s) and therapist from a clinical perspective.
3. Relate the marked prosodic examples to the relevant moments of the therapy.
4. Identify methodological limitations visible in the data.
5. Propose follow-up hypotheses testable with the same corpus.

Write in English, academic but clear tone, 500–800 words, with subheadings."
}

# Builds the HTML v2. Compatible with the old signature but with more parameters.
build_report_v2 <- function(text_block, features, overlaps, lmm, posthoc,
                            notes, sess_meta = NULL,
                            conv_lmm = NULL, lex_metrics = NULL,
                            pos_summary_df = NULL, selected_examples = NULL,
                            examples_html = NULL,
                            ai_interpretation = NULL) {
  esc <- function(x) htmltools::htmlEscape(as.character(x))
  tbl <- function(df) {
    if (is.null(df) || !is.data.frame(df) || nrow(df) == 0)
      return("<p class='note'>No data.</p>")
    ths  <- paste0("<th>", esc(names(df)), "</th>", collapse = "")
    rows <- apply(df, 1, function(r)
      paste0("<tr>", paste0("<td>", esc(r), "</td>", collapse = ""), "</tr>"))
    sprintf('<table><thead><tr>%s</tr></thead><tbody>%s</tbody></table>',
            ths, paste(rows, collapse = ""))
  }
  sec <- function(id, title, role, hint, body) {
    sprintf('<section id="%s" data-ai-role="%s" data-ai-hint="%s"><h2>%s</h2>%s</section>',
            id, role, esc(hint), esc(title), body)
  }

  secs <- ""

  # 1. Executive summary
  n_sess <- length(unique(features$therapy_num %||% integer(0)))
  n_par  <- length(unique(features$couple      %||% character(0)))
  n_feat <- nrow(features %||% data.frame())
  has_trans <- "text" %in% names(features %||% list()) &&
               any(!is.na((features %||% list())$text))
  resumen <- sprintf("<ul><li>Couples: <b>%d</b></li><li>Unique sessions: <b>%d</b></li><li>Acoustic segments: <b>%d</b></li><li>Transcription: %s</li></ul>",
    n_par, n_sess, n_feat, if (has_trans) "yes" else "no")
  secs <- paste0(secs, sec("s_resumen","Executive summary","overview",
    "General overview of the analysed corpus.", resumen))

  # 2. Researcher notes
  if (nchar(trimws(notes %||% "")) > 0)
    secs <- paste0(secs, sec("s_notas","Researcher notes","context",
      "Hypotheses, sample context, and qualitative observations.",
      sprintf('<div class="nbox">%s</div>', esc(notes))))

  # 3. Descriptives
  if (!is.null(features) && nrow(features) > 0) {
    d <- features |>
      dplyr::filter(speaker %in% c("man","woman","therapist")) |>
      dplyr::group_by(couple, therapy_num, speaker) |>
      dplyr::summarise(M_F0   = round(mean(f0_mean, na.rm = TRUE), 1),
                       SD_F0  = round(sd(f0_mean,   na.rm = TRUE), 1),
                       M_INT  = round(mean(intensity_mean, na.rm = TRUE), 1),
                       n = dplyr::n(), .groups = "drop")
    secs <- paste0(secs, sec("s_desc","Descriptives by couple, session and speaker",
      "descriptives",
      "Means and SD of F0 and intensity. Basis for subsequent comparisons.",
      tbl(d)))
  }

  # 4. LMM
  if (!is.null(lmm) && nrow(lmm) > 0) {
    tb <- lmm |>
      dplyr::mutate(dplyr::across(dplyr::where(is.double), ~round(., 3))) |>
      dplyr::select(dplyr::any_of(c("label","efecto","F_value","p_value","p_adj","eta2_p","sig")))
    secs <- paste0(secs, sec("s_lmm","Mixed linear models",
      "inferential",
      "parameter ~ session × speaker + quartile + (1|couple). p_adj=BH.",
      tbl(tb)))
  }

  # 5. Post-hoc
  if (!is.null(posthoc) && nrow(posthoc) > 0) {
    ph <- posthoc |>
      dplyr::filter(!is.na(p.value), p.value < 0.05) |>
      dplyr::mutate(dplyr::across(dplyr::where(is.double), ~round(., 4)))
    if (nrow(ph) > 0)
      secs <- paste0(secs, sec("s_posthoc","Significant post-hoc","inferential",
        "Tukey contrasts between session × speaker combinations.",
        tbl(ph)))
  }

  # 6. Convergence
  if (!is.null(conv_lmm) && is.data.frame(conv_lmm) && nrow(conv_lmm) > 0)
    secs <- paste0(secs, sec("s_conv","Patient ↔ therapist prosodic convergence",
      "convergence",
      "Z-normalised Euclidean distance between patient and therapist per session.",
      tbl(conv_lmm)))

  # 7. Linguistics (POS)
  if (!is.null(lex_metrics) && is.data.frame(lex_metrics) && nrow(lex_metrics) > 0)
    secs <- paste0(secs, sec("s_lex","Lexical metrics by speaker","linguistic",
      "TTR, lexical density, Yule's K.", tbl(lex_metrics)))
  if (!is.null(pos_summary_df) && is.data.frame(pos_summary_df) &&
      nrow(pos_summary_df) > 0)
    secs <- paste0(secs, sec("s_pos","POS distribution by speaker and quartile",
      "linguistic",
      "% of morphosyntactic categories within each speaker × quartile combination.",
      tbl(pos_summary_df)))

  # 8. Selected examples
  if (!is.null(examples_html) && nchar(examples_html) > 0)
    secs <- paste0(secs, sec("s_ej","Selected prosodic examples","examples",
      "Examples manually marked by the researcher.", examples_html))

  # 9. Free text block (backwards-compat)
  if (!is.null(text_block) && nzchar(text_block))
    secs <- paste0(secs, sec("s_bloque","Results block (text)","raw",
      "Plain-text version for pasting into chat.",
      sprintf('<pre class="cpre">%s</pre>', esc(text_block))))

  # 10. AI interpretation (if already called)
  if (!is.null(ai_interpretation) && nzchar(ai_interpretation))
    secs <- paste0(secs, sec("s_ai","AI-generated interpretation","ai_output",
      "Automatic LLM synthesis based on this report.",
      sprintf('<div class="ai-box">%s</div>',
              gsub("\n","<br>", esc(ai_interpretation)))))

  # Hidden JSON block + recommended prompt
  aijson <- ai_context_json(features, lmm, posthoc, conv_lmm, lex_metrics,
                            selected_examples, notes, sess_meta)
  prompt <- ai_prompt_template()

  sprintf('<!DOCTYPE html><html lang="en"><head>
<meta charset="UTF-8"><title>AcusTera — Report</title>
<link href="https://fonts.googleapis.com/css2?family=Syne:wght@700;800&family=IBM+Plex+Mono:wght@400&family=IBM+Plex+Sans:wght@400;500&display=swap" rel="stylesheet">
<style>
*{box-sizing:border-box;margin:0;padding:0}
body{background:#fff;color:#222;font-family:"IBM Plex Sans",sans-serif;
     font-size:14px;line-height:1.7;max-width:1000px;margin:0 auto;padding:48px 32px}
header{border-bottom:2px solid #2C7BB6;padding-bottom:20px;margin-bottom:36px}
.brand{font-family:"IBM Plex Mono";font-size:12px;color:#2C7BB6;letter-spacing:.1em;margin-bottom:10px}
h1{font-family:"Syne";font-size:28px;font-weight:800;color:#222}
.sub{color:#666;margin-top:4px;font-size:13px}
section{margin-bottom:40px}
h2{font-family:"Syne";font-size:18px;color:#2C7BB6;padding-bottom:8px;
   border-bottom:1px solid #e0e0e0;margin-bottom:14px}
.note{font-size:12px;color:#888;margin-bottom:10px}
table{width:100%%;border-collapse:collapse;font-family:"IBM Plex Mono";font-size:11px;margin-top:8px}
th{background:#f5f6fa;color:#555;text-transform:uppercase;font-size:10px;
   letter-spacing:.07em;padding:8px 10px;border-bottom:1px solid #e0e0e0;text-align:left}
td{padding:6px 10px;border-bottom:1px solid #f0f0f0;color:#333}
tr:hover td{background:#f9f9f9}
.cpre{background:#f5f6fa;border:1px solid #e0e0e0;border-radius:6px;padding:18px;
      font-family:"IBM Plex Mono";font-size:11px;color:#2C7BB6;
      white-space:pre-wrap;overflow:auto;max-height:500px}
.nbox{background:#f0f6ff;border-left:3px solid #2C7BB6;padding:12px 16px;
      border-radius:4px;font-size:13px;color:#444;white-space:pre-wrap}
.ai-box{background:#f7f9fc;border:1px solid #d7e3f0;border-radius:6px;padding:18px;line-height:1.7}
nav.toc{font-size:12px;background:#fafbff;border:1px solid #e2e6ef;border-radius:4px;padding:12px 16px;margin-bottom:24px}
nav.toc a{color:#2C7BB6;text-decoration:none;margin-right:12px}
.ai-prompt{background:#fff8e5;border:1px dashed #f39c12;border-radius:4px;padding:14px;font-size:12px;white-space:pre-wrap;margin-top:18px}
</style></head><body>
<header>
  <div class="brand">\u25C8 AcusTera</div>
  <h1>Acoustic analysis report</h1>
  <div class="sub">Couple therapy — longitudinal analysis · %s</div>
</header>
<nav class="toc">
  <b>Index:</b>
  <a href="#s_resumen">Summary</a>
  <a href="#s_desc">Descriptives</a>
  <a href="#s_lmm">LMM</a>
  <a href="#s_conv">Convergence</a>
  <a href="#s_lex">Lexical</a>
  <a href="#s_ej">Examples</a>
  <a href="#s_ai">AI</a>
</nav>
%s
<section id="s_ai_prompt" data-ai-role="prompt">
  <h2>Suggested AI prompt</h2>
  <p class="note">Copy this prompt and the entire report to the Claude/ChatGPT chat to obtain an automatic interpretation.</p>
  <div class="ai-prompt">%s</div>
</section>
<script type="application/json" id="acustera_ai_context">
%s
</script>
</body></html>',
    format(Sys.time(), "%d/%m/%Y %H:%M"), secs, esc(prompt), aijson)
}
